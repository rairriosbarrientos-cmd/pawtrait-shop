// Downloads the sample images, compresses them to WebP and saves them in public/muestras.
// Runs before `vite build`; if anything fails, the store keeps using the CDN images (never breaks the build).
import { mkdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { MUESTRAS_REMOTAS } from '../src/catalogo.js';

const locales = {};
await mkdir(new URL('../public/muestras/', import.meta.url), { recursive: true });
for (const [id, url] of Object.entries(MUESTRAS_REMOTAS)) {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(20000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const webp = await sharp(Buffer.from(await res.arrayBuffer())).resize({ width: 900, withoutEnlargement: true }).webp({ quality: 82 }).toBuffer();
    await writeFile(new URL(`../public/muestras/${id}.webp`, import.meta.url), webp);
    locales[id] = `/muestras/${id}.webp`;
    console.log(`sample ${id}: ${Math.round(webp.length / 1024)} KB`);
  } catch (e) {
    console.warn(`sample ${id}: staying on the CDN (${e.message})`);
  }
}
await writeFile(new URL('../src/muestras.local.js', import.meta.url),
  `// Generated by scripts/muestras.mjs on deploy (npm run build). Empty = the CDN images are used.\nexport default ${JSON.stringify(locales, null, 2)};\n`);
